//! Stubs generated from the connected board.
//!
//! Published stubs cover stock firmware. Custom builds add modules (`ulab`,
//! user C modules, frozen drivers) the language server then reports as
//! missing. For those, the board describes each module (`py/introspect.py`:
//! names, kinds, classes and their members) and `.pyi` files are written with
//! loose signatures (`*args, **kwargs -> Any`). They're merged into a copy of
//! the stub set, cached per stub set, firmware build and module list.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use serde::Deserialize;
use sha2::{Digest, Sha256};

use super::stubs::{write_versions, StubSet};
use crate::error::{Error, Result};
use crate::repl::session::Session;

/// Modules never introspected: importing them runs setup code or the program.
const SKIP: &[&str] = &["__main__", "main", "boot", "inisetup", "flashbdev", "webrepl_setup", "this", "antigravity", "upip"];

/// Top-level modules listed by `help("modules")`.
pub fn parse_module_list(text: &str) -> BTreeSet<String> {
    text.lines()
        .take_while(|l| !l.starts_with("Plus any modules"))
        .flat_map(str::split_whitespace)
        .map(|m| m.split('/').next().unwrap_or(m).to_string())
        .filter(|m| !m.is_empty() && m.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'))
        .collect()
}

/// Board modules worth generating stubs for: not covered by the stub set,
/// not private, and safe to import.
pub fn missing_modules(board: &BTreeSet<String>, typeshed_stdlib: &Path) -> Vec<String> {
    let covered: BTreeSet<String> = std::fs::read_to_string(typeshed_stdlib.join("VERSIONS"))
        .unwrap_or_default()
        .lines()
        .filter_map(|l| l.split(':').next())
        .map(|m| m.trim().to_string())
        .collect();
    board
        .iter()
        .filter(|m| !m.starts_with('_') && !SKIP.contains(&m.as_str()) && !covered.contains(*m))
        .filter(|m| !covered.contains(&format!("u{m}")) && !(m.starts_with('u') && covered.contains(&m[1..])))
        .cloned()
        .collect()
}

#[derive(Debug, Deserialize)]
pub struct ModuleInfo {
    pub module: String,
    #[serde(default)]
    pub members: Vec<(String, String, String)>,
    #[serde(default)]
    pub classes: BTreeMap<String, Vec<(String, String, String)>>,
    #[serde(default)]
    pub error: Option<String>,
}

pub fn parse_infos(text: &str) -> Vec<ModuleInfo> {
    text.lines().filter_map(|l| serde_json::from_str::<ModuleInfo>(l.trim()).ok()).filter(|m| m.error.is_none()).collect()
}

const KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del", "elif",
    "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal", "not", "or",
    "pass", "raise", "return", "try", "while", "with", "yield",
];

fn ident(name: &str) -> bool {
    let mut c = name.chars();
    c.next().is_some_and(|f| f.is_ascii_alphabetic() || f == '_')
        && name.chars().all(|ch| ch.is_ascii_alphanumeric() || ch == '_')
        && !KEYWORDS.contains(&name)
}

fn value_type(kind: &str) -> &str {
    match kind {
        "int" | "float" | "str" | "bool" | "bytes" | "bytearray" | "tuple" | "list" | "dict" => kind,
        "NoneType" => "None",
        _ => "Any",
    }
}

/// The `.pyi` text for one module.
pub fn render_module(info: &ModuleInfo, origin: &str) -> String {
    let mut out = format!(
        "# Generated by Microbe by introspecting {origin}.\n# Names are exact; signatures aren't known, so arguments and results are loose.\nfrom typing import Any\n\n"
    );
    for (name, kind, _) in &info.members {
        if !ident(name) {
            continue;
        }
        match kind.as_str() {
            "function" => out.push_str(&format!("def {name}(*args: Any, **kwargs: Any) -> Any: ...\n")),
            "class" => {
                out.push_str(&format!("\nclass {name}:\n"));
                out.push_str("    def __init__(self, *args: Any, **kwargs: Any) -> None: ...\n");
                for (m, mk, _) in info.classes.get(name).into_iter().flatten() {
                    if !ident(m) || m == "__init__" {
                        continue;
                    }
                    match mk.as_str() {
                        "function" => out.push_str(&format!("    def {m}(self, *args: Any, **kwargs: Any) -> Any: ...\n")),
                        k => out.push_str(&format!("    {m}: {}\n", value_type(k))),
                    }
                }
                out.push('\n');
            }
            "module" => {} // submodules get their own file
            k => out.push_str(&format!("{name}: {}\n", value_type(k))),
        }
    }
    // Attributes added at runtime still resolve.
    out.push_str("\ndef __getattr__(name: str) -> Any: ...\n");
    out
}

/// Write generated stubs into `stdlib`; modules with submodules become packages.
pub fn write_stubs(stdlib: &Path, infos: &[ModuleInfo], origin: &str) -> Result<Vec<String>> {
    let packages: BTreeSet<&str> = infos.iter().filter_map(|i| i.module.rsplit_once('.').map(|(p, _)| p)).collect();
    let mut written = Vec::new();
    for info in infos {
        let parts: Vec<&str> = info.module.split('.').collect();
        if !parts.iter().all(|p| ident(p)) {
            continue;
        }
        let rel = if packages.contains(info.module.as_str()) {
            format!("{}/__init__.pyi", parts.join("/"))
        } else {
            format!("{}.pyi", parts.join("/"))
        };
        let path = stdlib.join(&rel);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        std::fs::write(&path, render_module(info, origin))?;
        written.push(info.module.clone());
    }
    Ok(written)
}

/// Ask the board which modules it has and generate stubs for those `base`
/// doesn't cover. Returns `base` unchanged when nothing is missing.
pub async fn extend(session: &Session, base: &StubSet, cache: &Path) -> Result<StubSet> {
    let profile = session.profile();
    let base_dir = Path::new(&base.typeshed);
    let mut raw = session.raw().await?;
    let listed = raw.exec_str(&crate::scripts::render(&profile, "modules", &[])?).await;
    let listed = match listed {
        Ok(t) => t,
        Err(e) => return raw.finish_with(Err(e)).await,
    };
    let missing = missing_modules(&parse_module_list(&listed), &base_dir.join("stdlib"));
    if missing.is_empty() {
        raw.finish().await?;
        return Ok(base.clone());
    }

    let info = session.info.lock().unwrap().clone().unwrap_or_default();
    let mut h = Sha256::new();
    h.update(format!("{}|{}|{}|{}", base.key, info.build, info.version, missing.join(",")));
    let key = format!("{}+board-{}", base.key, &hex::encode(h.finalize())[..10]);
    let set_dir = cache.join("sets").join(&key);
    let marker = set_dir.join("stubset.json");
    if let Ok(set) = std::fs::read(&marker).map_err(Error::from).and_then(|d| Ok(serde_json::from_slice::<StubSet>(&d)?)) {
        raw.finish().await?;
        return Ok(set);
    }

    // A few modules per exec keeps each reply small on boards with little RAM.
    let mut infos = Vec::new();
    for chunk in missing.chunks(6) {
        let list = serde_json::to_string(chunk)?;
        let code = crate::scripts::render(&profile, "introspect", &[("modules", crate::scripts::Py::Str(&list))])?;
        match raw.exec_str(&code).await {
            Ok(out) => infos.extend(parse_infos(&out)),
            Err(e) => return raw.finish_with(Err(e)).await,
        }
    }
    raw.finish().await?;

    let tmp = set_dir.with_extension("tmp");
    let _ = std::fs::remove_dir_all(&tmp);
    copy_tree(base_dir, &tmp)?;
    let origin = match info.build.as_str() {
        "" => format!("MicroPython {}", info.version),
        b => format!("{b} running MicroPython {}", info.version),
    };
    let written = write_stubs(&tmp.join("stdlib"), &infos, &origin)?;
    write_versions(&tmp.join("stdlib"))?;
    let _ = std::fs::remove_dir_all(&set_dir);
    std::fs::rename(&tmp, &set_dir)?;
    let mut packages = base.packages.clone();
    let top: BTreeSet<&str> = written.iter().map(|m| m.split('.').next().unwrap_or(m)).collect();
    packages.push(format!("from the board: {}", top.into_iter().collect::<Vec<_>>().join(", ")));
    let set = StubSet { key, typeshed: set_dir.display().to_string(), packages, version: base.version.clone() };
    std::fs::write(&marker, serde_json::to_vec_pretty(&set)?)?;
    Ok(set)
}

fn copy_tree(src: &Path, dst: &Path) -> Result<()> {
    std::fs::create_dir_all(dst)?;
    for e in std::fs::read_dir(src)? {
        let e = e?;
        let to = dst.join(e.file_name());
        if e.file_type()?.is_dir() {
            copy_tree(&e.path(), &to)?;
        } else if e.file_name() != "stubset.json" {
            std::fs::copy(e.path(), to)?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn module_list() {
        let text = "__main__          btree             io\n_asyncio          asyncio/core      json\nulab              mip/__init__      main\nPlus any modules on the filesystem\n";
        let mods = parse_module_list(text);
        assert!(mods.contains("asyncio") && mods.contains("mip") && mods.contains("ulab"));
        assert!(!mods.iter().any(|m| m.contains('/')));
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("VERSIONS"), "json: 3.0-\nio: 3.0-\nasyncio: 3.0-\n").unwrap();
        assert_eq!(missing_modules(&mods, dir.path()), vec!["btree", "mip", "ulab"]);
    }

    #[test]
    fn renders_pyi() {
        let infos = parse_infos(concat!(
            r#"{"module": "ulab", "members": [["numpy", "module", "module"], ["__version__", "str", "str"]], "classes": {}}"#, "\n",
            r#"{"module": "ulab.numpy", "members": [["array", "class", "type"], ["zeros", "function", "function"], ["pi", "float", "float"], ["def", "int", "int"]], "classes": {"array": [["shape", "object", "property"], ["reshape", "function", "function"]]}}"#, "\n",
            r#"{"module": "broken", "error": "ImportError()"}"#, "\n",
        ));
        assert_eq!(infos.len(), 2);
        let dir = tempfile::tempdir().unwrap();
        let written = write_stubs(dir.path(), &infos, "TEST").unwrap();
        assert_eq!(written, vec!["ulab", "ulab.numpy"]);
        let init = std::fs::read_to_string(dir.path().join("ulab/__init__.pyi")).unwrap();
        assert!(init.contains("__version__: str"));
        let np = std::fs::read_to_string(dir.path().join("ulab/numpy.pyi")).unwrap();
        assert!(np.contains("class array:\n    def __init__(self, *args: Any, **kwargs: Any) -> None: ...\n"));
        assert!(np.contains("    def reshape(self, *args: Any, **kwargs: Any) -> Any: ...\n"));
        assert!(np.contains("    shape: Any\n") && np.contains("def zeros(*args: Any") && np.contains("pi: float"));
        assert!(!np.contains("def: int"), "keywords are skipped");
    }
}
