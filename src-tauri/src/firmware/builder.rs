//! Build MicroPython firmware from source in Docker.
//!
//! Recipes per port live in `src-tauri/builders.toml`: the toolchain image,
//! make arguments and the files to collect. A build:
//! 1. makes sure the image exists (building Microbe's own images from their
//!    Dockerfile when missing),
//! 2. runs one container that checks out the MicroPython tag (cached under
//!    `<cache>/build/src/`), builds mpy-cross and the port's submodules, then
//!    the firmware, optionally freezing the project's modules (a generated
//!    manifest) and adding user C modules,
//! 3. copies the artifacts to `<cache>/build/out/<id>/`, ready for the
//!    regular flash flow (a local file).
//!
//! Output streams line by line to the caller.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::sync::Arc;

use serde::{Deserialize, Serialize};
use tauri::ipc::Channel;
use tauri::State;
use tokio::io::{AsyncBufReadExt, AsyncWriteExt, BufReader};
use tokio_util::sync::CancellationToken;
use ts_rs::TS;

use crate::error::{Error, Result};
use crate::repl::quirks::version_matches;
use crate::state::AppState;

const BUILTIN: &str = include_str!("../../builders.toml");
const REPO: &str = "https://github.com/micropython/micropython.git";
/// Printed by the build script when it finished; anything else is a failure.
const DONE: &str = "MICROBE_BUILD_DONE";

#[derive(Debug, Deserialize)]
pub struct Builders {
    #[serde(default)]
    pub images: BTreeMap<String, ImageDef>,
    #[serde(default, rename = "builder")]
    pub builders: Vec<BuilderDef>,
}

#[derive(Debug, Deserialize)]
pub struct ImageDef {
    pub tag: String,
    pub dockerfile: String,
}

#[derive(Debug, Deserialize)]
pub struct BuilderDef {
    pub ports: Vec<String>,
    pub image: String,
    pub make_args: String,
    pub build_dir: String,
    #[serde(default)]
    pub c_modules: Option<String>,
    pub artifacts: Vec<Artifact>,
    #[serde(default)]
    pub idf: Vec<IdfRule>,
}

#[derive(Debug, Deserialize)]
pub struct Artifact {
    pub file: String,
    #[serde(default, rename = "as")]
    pub rename: Option<String>,
}

#[derive(Debug, Deserialize)]
pub struct IdfRule {
    pub micropython: String,
    pub idf: String,
}

impl Builders {
    pub fn builtin() -> Result<Self> {
        toml::from_str(BUILTIN).map_err(|e| Error::other(format!("builders.toml: {e}")))
    }

    pub fn for_port(&self, port: &str) -> Option<&BuilderDef> {
        self.builders.iter().find(|b| b.ports.iter().any(|p| p == port))
    }

    pub fn ports(&self) -> Vec<String> {
        self.builders.iter().flat_map(|b| b.ports.clone()).collect()
    }
}

#[derive(Debug, Clone, Deserialize, TS)]
#[ts(export)]
pub struct BuildRequest {
    pub port: String,
    /// Board id (`RPI_PICO`), or the variant for the unix port (`standard`).
    pub board: String,
    #[serde(default)]
    pub variant: Option<String>,
    /// MicroPython release (`1.24.1`) or a git ref (`master`).
    pub version: String,
    /// Project folder whose modules are frozen into the firmware.
    #[serde(default)]
    pub freeze_project: Option<String>,
    /// Folder with user C modules (`micropython.cmake` / `micropython.mk`).
    #[serde(default)]
    pub c_modules: Option<String>,
}

#[derive(Debug, Clone, Serialize, TS)]
#[ts(export)]
pub struct BuildResult {
    pub output_dir: String,
    /// Built files, ready to flash.
    pub artifacts: Vec<String>,
}

#[derive(Debug, Clone, Serialize, TS)]
#[ts(export)]
pub struct BuilderInfo {
    pub ports: Vec<String>,
    /// Docker is installed and its daemon answers.
    pub docker: bool,
    /// Why Docker can't be used, if it can't.
    pub problem: Option<String>,
}

/// Everything needed to run one build.
#[derive(Debug)]
pub struct BuildPlan {
    pub id: String,
    pub image: String,
    /// Build this image from a Dockerfile first, if it's missing.
    pub dockerfile: Option<String>,
    pub container: String,
    /// Arguments after `docker`.
    pub run_args: Vec<String>,
    pub script: String,
    pub out_dir: PathBuf,
    /// Manifest to write before the build (host path, contents).
    pub manifest: Option<(PathBuf, String)>,
}

/// `1.24.1` → `v1.24.1`; anything that isn't a version is a git ref.
pub fn git_ref(version: &str) -> String {
    let v = version.trim();
    if v.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("v{v}")
    } else {
        v.to_string()
    }
}

fn safe(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || "_-.".contains(c))
}

/// A manifest freezing the project's modules (not main.py / boot.py / tests).
pub fn project_manifest(files: &[String]) -> String {
    let mut out = String::from("# Generated by Microbe: the project's modules.\n");
    for rel in files {
        let name = rel.rsplit('/').next().unwrap_or(rel);
        let is_test = crate::testing::is_test_file(name) || rel.starts_with("tests/") || rel.starts_with("test/");
        if !rel.ends_with(".py") || is_test || rel == "main.py" || rel == "boot.py" {
            continue;
        }
        match rel.strip_prefix("lib/") {
            Some(inner) => out.push_str(&format!("module({inner:?}, base_path=\"/project/lib\")\n")),
            None => out.push_str(&format!("module({rel:?}, base_path=\"/project\")\n")),
        }
    }
    out
}

pub fn plan(builders: &Builders, req: &BuildRequest, work: &Path, id: &str) -> Result<BuildPlan> {
    let b = builders.for_port(&req.port).ok_or_else(|| Error::Unsupported(format!("no Docker build recipe for {}", req.port)))?;
    let variant = req.variant.as_deref().filter(|v| !v.is_empty());
    if !safe(&req.board) || !variant.is_none_or(safe) || !safe(&git_ref(&req.version)) {
        return Err(Error::other("board, variant and version may only use letters, digits, '_', '-' and '.'"));
    }
    let gref = git_ref(&req.version);
    let fill = |t: &str| {
        t.replace("{board}", &req.board)
            .replace("{variant_arg}", &variant.map(|v| format!(" BOARD_VARIANT={v}")).unwrap_or_default())
            .replace("{variant_suffix}", &variant.map(|v| format!("-{v}")).unwrap_or_default())
    };

    let (image, dockerfile) = match b.image.strip_prefix("local:") {
        Some(name) => {
            let def = builders.images.get(name).ok_or_else(|| Error::other(format!("builders.toml: no image {name}")))?;
            (def.tag.clone(), Some(def.dockerfile.clone()))
        }
        None if b.image.contains("{idf}") => {
            let version = if gref.starts_with('v') { &gref[1..] } else { "99" };
            let idf = b
                .idf
                .iter()
                .find(|r| version_matches(version, &r.micropython))
                .ok_or_else(|| Error::other(format!("no ESP-IDF version known for MicroPython {}", req.version)))?;
            (b.image.replace("{idf}", &idf.idf), None)
        }
        None => (b.image.clone(), None),
    };

    let container = format!("microbe-build-{id}");
    let mut run_args: Vec<String> = vec!["run".into(), "--rm".into(), "--name".into(), container.clone()];
    run_args.extend(["-v".into(), format!("{}:/work", work.display()), "-e".into(), "HOME=/tmp".into()]);
    #[cfg(target_os = "linux")]
    {
        // Keep the cache owned by the user, not root.
        let (uid, gid) = unsafe { (libc::getuid(), libc::getgid()) };
        run_args.extend(["--user".into(), format!("{uid}:{gid}")]);
    }
    let mut make_extra = String::new();
    let mut manifest = None;
    let mut manifest_step = String::new();
    if let Some(project) = &req.freeze_project {
        run_args.extend(["-v".into(), format!("{project}:/project:ro")]);
        let files: Vec<String> = crate::sync::local_files(Path::new(project), &[])?.into_iter().map(|(rel, _)| rel).collect();
        manifest = Some((work.join("manifests").join(format!("{id}.py")), project_manifest(&files)));
        let port_dir = format!("ports/{}", req.port);
        // Keep what the board freezes by default, then add the project.
        manifest_step = format!(
            "INC=\"\"\nfor f in {pd}/boards/{board}/manifest.py {pd}/variants/{board}/manifest.py {pd}/boards/manifest.py {pd}/variants/manifest.py; do\n  if [ -z \"$INC\" ] && [ -f \"$f\" ]; then INC=\"$SRC/$f\"; fi\ndone\n{{ [ -n \"$INC\" ] && printf 'include(\"%s\")\\n' \"$INC\"; cat /work/manifests/{id}.py; }} > /work/manifests/{id}-full.py\n",
            pd = port_dir,
            board = req.board,
        );
        make_extra.push_str(&format!(" FROZEN_MANIFEST=/work/manifests/{id}-full.py"));
    }
    if let Some(dir) = &req.c_modules {
        let value = b.c_modules.as_deref().ok_or_else(|| Error::Unsupported(format!("{} builds don't take C modules", req.port)))?;
        run_args.extend(["-v".into(), format!("{dir}:/cmods:ro")]);
        make_extra.push_str(&format!(" USER_C_MODULES={value}"));
    }
    run_args.extend([image.clone(), "bash".into(), "-c".into()]);

    let make_args = fill(&b.make_args);
    let build_dir = fill(&b.build_dir);
    let copies: String = b
        .artifacts
        .iter()
        .map(|a| format!("[ -f \"$B/{f}\" ] && cp \"$B/{f}\" \"$OUT/{to}\"\n", f = a.file, to = a.rename.as_deref().unwrap_or(&a.file)))
        .collect();
    let update = if gref.starts_with('v') {
        String::new()
    } else {
        format!("git -C \"$SRC\" fetch --depth 1 origin {gref} && git -C \"$SRC\" reset --hard FETCH_HEAD\n")
    };
    let script = format!(
        "set -e\ngit config --global --add safe.directory '*' 2>/dev/null || true\n\
         SRC=/work/src/micropython-{gref}\n\
         if [ ! -d \"$SRC/.git\" ]; then rm -rf \"$SRC\"; git clone --depth 1 --branch {gref} {REPO} \"$SRC\"; fi\n\
         {update}cd \"$SRC\"\n\
         echo '== mpy-cross'\nmake -C mpy-cross -j\"$(nproc)\"\n\
         echo '== submodules'\nmake -C ports/{port} {make_args} submodules\n\
         {manifest_step}\
         echo '== firmware'\nmake -C ports/{port} {make_args}{make_extra} -j\"$(nproc)\"\n\
         B=ports/{port}/{build_dir}\nOUT=/work/out/{id}\nmkdir -p \"$OUT\"\n\
         {copies}echo {DONE}\n",
        port = req.port,
    );
    Ok(BuildPlan { id: id.to_string(), image, dockerfile, container, run_args, script, out_dir: work.join("out").join(id), manifest })
}

/// Runs docker, streaming output lines to `log`.
pub struct Docker {
    pub exe: PathBuf,
}

impl Docker {
    pub fn find() -> Result<Self> {
        let exe = crate::tools::which("docker")
            .ok_or_else(|| Error::Unsupported("Docker isn't installed (or not on PATH); get Docker Desktop or the docker engine".into()))?;
        Ok(Self { exe })
    }

    /// Run to completion; `Ok(true)` on exit status 0. Output lines go to `log`.
    async fn run(&self, args: &[String], stdin: Option<&str>, log: &(dyn Fn(String) + Send + Sync), cancel: &CancellationToken) -> Result<bool> {
        let mut cmd = tokio::process::Command::new(&self.exe);
        cmd.args(args).stdout(Stdio::piped()).stderr(Stdio::piped()).stdin(if stdin.is_some() { Stdio::piped() } else { Stdio::null() });
        cmd.kill_on_drop(true);
        let mut child = cmd.spawn()?;
        if let (Some(text), Some(mut pipe)) = (stdin, child.stdin.take()) {
            pipe.write_all(text.as_bytes()).await?;
            drop(pipe);
        }
        let (tx, mut rx) = tokio::sync::mpsc::unbounded_channel::<String>();
        for stream in [child.stdout.take().map(|s| Box::new(s) as Box<dyn tokio::io::AsyncRead + Unpin + Send>), child.stderr.take().map(|s| Box::new(s) as _)].into_iter().flatten() {
            let tx = tx.clone();
            tokio::spawn(async move {
                let mut lines = BufReader::new(stream).lines();
                while let Ok(Some(l)) = lines.next_line().await {
                    let _ = tx.send(l);
                }
            });
        }
        drop(tx);
        loop {
            tokio::select! {
                line = rx.recv() => match line {
                    Some(l) => log(l),
                    None => break,
                },
                _ = cancel.cancelled() => {
                    let _ = child.kill().await;
                    return Err(Error::other("build cancelled"));
                }
            }
        }
        Ok(child.wait().await?.success())
    }

    pub async fn check(&self) -> Result<()> {
        let quiet = |_: String| {};
        let args = ["info".to_string(), "--format".into(), "{{.ServerVersion}}".into()];
        if self.run(&args, None, &quiet, &CancellationToken::new()).await? {
            Ok(())
        } else {
            Err(Error::Unsupported("Docker isn't running: start Docker Desktop (or the docker service)".into()))
        }
    }

    pub async fn build(&self, plan: &BuildPlan, log: &(dyn Fn(String) + Send + Sync), cancel: &CancellationToken) -> Result<BuildResult> {
        if let Some(df) = &plan.dockerfile {
            let present = self.run(&["image".into(), "inspect".into(), plan.image.clone()], None, &|_| {}, cancel).await?;
            if !present {
                log(format!("== building the toolchain image {} (first build only)", plan.image));
                if !self.run(&["build".into(), "-t".into(), plan.image.clone(), "-".into()], Some(df), log, cancel).await? {
                    return Err(Error::other(format!("couldn't build the image {}", plan.image)));
                }
            }
        }
        if let Some((path, text)) = &plan.manifest {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)?;
            }
            std::fs::write(path, text)?;
        }
        let _ = std::fs::remove_dir_all(&plan.out_dir);
        let finished = std::sync::atomic::AtomicBool::new(false);
        let watch = |l: String| {
            if l.trim() == DONE {
                finished.store(true, std::sync::atomic::Ordering::Relaxed);
            } else {
                log(l);
            }
        };
        let mut args = plan.run_args.clone();
        args.push(plan.script.clone());
        let cancelled = async {
            cancel.cancelled().await;
            let _ = tokio::process::Command::new(&self.exe).args(["kill", &plan.container]).output().await;
        };
        let ok = tokio::select! {
            r = self.run(&args, None, &watch, cancel) => r?,
            _ = cancelled => return Err(Error::other("build cancelled")),
        };
        if !ok || !finished.load(std::sync::atomic::Ordering::Relaxed) {
            return Err(Error::other("the build failed; see the log"));
        }
        let mut artifacts: Vec<String> = std::fs::read_dir(&plan.out_dir)
            .map(|d| d.flatten().map(|e| e.path().display().to_string()).collect())
            .unwrap_or_default();
        artifacts.sort();
        if artifacts.is_empty() {
            return Err(Error::other("the build finished but produced none of the expected files"));
        }
        Ok(BuildResult { output_dir: plan.out_dir.display().to_string(), artifacts })
    }
}

/// The running build's cancel token.
#[derive(Default)]
pub struct Builds {
    current: std::sync::Mutex<Option<CancellationToken>>,
}

#[tauri::command]
pub async fn firmware_builders() -> Result<BuilderInfo> {
    let ports = Builders::builtin()?.ports();
    let problem = match Docker::find() {
        Ok(d) => d.check().await.err().map(|e| e.to_string()),
        Err(e) => Some(e.to_string()),
    };
    Ok(BuilderInfo { ports, docker: problem.is_none(), problem })
}

#[tauri::command]
pub async fn firmware_build(state: State<'_, AppState>, request: BuildRequest, log: Channel<String>) -> Result<BuildResult> {
    let docker = Docker::find()?;
    docker.check().await?;
    let work = state.cache_dir("build")?;
    let id = format!(
        "{}-{}-{}",
        request.port,
        request.board.to_lowercase(),
        std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0)
    );
    let plan = plan(&Builders::builtin()?, &request, &work, &id)?;
    let cancel = CancellationToken::new();
    {
        let mut cur = state.builds.current.lock().unwrap();
        if cur.is_some() {
            return Err(Error::Busy("a firmware build is already running"));
        }
        *cur = Some(cancel.clone());
    }
    let log = Arc::new(log);
    let sink = {
        let log = log.clone();
        move |l: String| {
            let _ = log.send(l);
        }
    };
    let _ = log.send(format!("== {} in {}", request.port, plan.image));
    let res = docker.build(&plan, &sink, &cancel).await;
    *state.builds.current.lock().unwrap() = None;
    res
}

#[tauri::command]
pub fn firmware_build_cancel(state: State<'_, AppState>) {
    if let Some(c) = state.builds.current.lock().unwrap().take() {
        c.cancel();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn req(port: &str, board: &str, variant: Option<&str>, version: &str) -> BuildRequest {
        BuildRequest { port: port.into(), board: board.into(), variant: variant.map(Into::into), version: version.into(), freeze_project: None, c_modules: None }
    }

    #[test]
    fn recipes_parse_and_cover_ports() {
        let b = Builders::builtin().unwrap();
        for port in ["esp32", "esp8266", "rp2", "stm32", "samd", "unix"] {
            assert!(b.for_port(port).is_some(), "{port}");
        }
    }

    #[test]
    fn esp32_plan_picks_idf_and_artifacts() {
        let b = Builders::builtin().unwrap();
        let p = plan(&b, &req("esp32", "ESP32_GENERIC_S3", Some("SPIRAM_OCT"), "1.24.1"), Path::new("/c/build"), "x").unwrap();
        assert_eq!(p.image, "espressif/idf:v5.2.2");
        assert!(p.dockerfile.is_none());
        assert!(p.script.contains("git clone --depth 1 --branch v1.24.1"));
        assert!(p.script.contains("make -C ports/esp32 BOARD=ESP32_GENERIC_S3 BOARD_VARIANT=SPIRAM_OCT -j"));
        assert!(p.script.contains("B=ports/esp32/build-ESP32_GENERIC_S3-SPIRAM_OCT"));
        assert!(p.script.contains("cp \"$B/micropython.bin\" \"$OUT/firmware.app-bin\""));
        assert!(p.run_args.contains(&"/c/build:/work".to_string()));
        assert_eq!(plan(&b, &req("esp32", "ESP32_GENERIC", None, "master"), Path::new("/c"), "y").unwrap().image, "espressif/idf:v5.4.2");
        assert_eq!(plan(&b, &req("esp32", "ESP32_GENERIC", None, "1.21.0"), Path::new("/c"), "y").unwrap().image, "espressif/idf:v5.0.2");
    }

    #[test]
    fn local_images_frozen_projects_and_c_modules() {
        let b = Builders::builtin().unwrap();
        let project = tempfile::tempdir().unwrap();
        for f in ["main.py", "boot.py", "app.py", "lib/sensor/bme.py", "tests/test_x.py", "test_y.py", "README.md"] {
            let p = project.path().join(f);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(p, "").unwrap();
        }
        let mut r = req("rp2", "RPI_PICO", None, "1.24.0");
        r.freeze_project = Some(project.path().display().to_string());
        r.c_modules = Some("/my/cmods".into());
        let p = plan(&b, &r, Path::new("/c/build"), "z").unwrap();
        assert_eq!(p.image, "microbe-build-arm:1");
        assert!(p.dockerfile.as_deref().unwrap().contains("gcc-arm-none-eabi"));
        assert!(p.script.contains("FROZEN_MANIFEST=/work/manifests/z-full.py USER_C_MODULES=/cmods/micropython.cmake"));
        assert!(p.script.contains("ports/rp2/boards/RPI_PICO/manifest.py"));
        let (path, text) = p.manifest.unwrap();
        assert_eq!(path, Path::new("/c/build/manifests/z.py"));
        assert_eq!(text, "# Generated by Microbe: the project's modules.\nmodule(\"app.py\", base_path=\"/project\")\nmodule(\"sensor/bme.py\", base_path=\"/project/lib\")\n");
        assert!(p.run_args.iter().any(|a| a.ends_with(":/project:ro")) && p.run_args.contains(&"/my/cmods:/cmods:ro".to_string()));
    }

    #[test]
    fn rejects_unsafe_names_and_unknown_ports() {
        let b = Builders::builtin().unwrap();
        assert!(plan(&b, &req("rp2", "PICO; rm -rf /", None, "1.24.0"), Path::new("/c"), "a").is_err());
        assert!(plan(&b, &req("rp2", "RPI_PICO", None, "$(evil)"), Path::new("/c"), "a").is_err());
        assert!(plan(&b, &req("zephyr-x", "B", None, "1.24.0"), Path::new("/c"), "a").is_err());
        assert_eq!(git_ref("1.24.1"), "v1.24.1");
        assert_eq!(git_ref("v1.24.1"), "v1.24.1");
    }
}
